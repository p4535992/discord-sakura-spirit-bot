"""Operational climate profiles: loading, validation and range resolution.

``climate_profiles.json`` is generated by ``scripts/build_operational_profiles.py``
from the versioned workbook catalog. It holds the *stable* monthly ranges the
engine may use, and declares the provenance of every field, so a randomized
workbook snapshot is never presented as a climate normal.

This module is pure: it reads JSON, validates it and resolves the effective
ranges for one channel. It never touches Discord, the database or the clock.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Mapping

DEFAULT_PROFILES_PATH = Path(__file__).with_name("climate_profiles.json")

# Physical sanity bounds: an administrator override may widen a preset range but
# never beyond what the model can represent.
GLOBAL_BOUNDS: dict[str, tuple[float, float]] = {
    "temp_min_c": (-90.0, 60.0),
    "temp_max_c": (-90.0, 60.0),
    "humidity_pct": (0.0, 100.0),
    "wind_speed_kmh": (0.0, 400.0),
    "wind_gust_kmh": (0.0, 450.0),
    "cloud_cover_pct": (0.0, 100.0),
    "precipitation_probability_pct": (0.0, 100.0),
    "visibility_km": (0.0, 100.0),
    "pressure_hpa": (800.0, 1100.0),
}

PERCENT_FIELDS = frozenset({"humidity_pct", "cloud_cover_pct", "precipitation_probability_pct"})
NON_NEGATIVE_FIELDS = frozenset({"wind_speed_kmh", "wind_gust_kmh", "visibility_km"})

WIND_DIRECTIONS = ("N", "NE", "E", "SE", "S", "SW", "W", "NW")


class ProfileError(ValueError):
    """Base error for the climate profile layer."""


class UnknownProfileError(ProfileError):
    """The requested preset slug or alias does not exist."""


class ProfileValidationError(ProfileError):
    """A profile or an administrator override violates a documented rule."""


@dataclass(frozen=True)
class NumericRange:
    """An inclusive numeric range with a hard ``min <= max`` invariant."""

    min: float
    max: float

    def __post_init__(self) -> None:
        if self.min > self.max:
            raise ProfileValidationError(f"invalid range: min {self.min} > max {self.max}")

    def clamp(self, value: float) -> float:
        return max(self.min, min(self.max, value))

    def contains(self, value: float) -> bool:
        return self.min <= value <= self.max

    def to_dict(self) -> dict[str, float]:
        return {"min": self.min, "max": self.max}


@dataclass(frozen=True)
class MonthProfile:
    """One operational month of a climate: stable ranges, not snapshots."""

    month: int
    name: str
    precipitation_probability: float
    temp_cold_c: float
    temp_avg_c: float
    temp_hot_c: float
    humidity: NumericRange
    wind_speed: NumericRange
    wind_gust_max_kmh: float
    cloud_cover: NumericRange
    visibility: NumericRange
    pressure: NumericRange
    preferred_wind_directions: tuple[str, ...]

    def __post_init__(self) -> None:
        if not 1 <= self.month <= 12:
            raise ProfileValidationError(f"month out of range: {self.month}")
        if not 0.0 <= self.precipitation_probability <= 1.0:
            raise ProfileValidationError(
                f"month {self.month}: precipitation probability must be a fraction"
            )
        if not self.temp_cold_c <= self.temp_avg_c <= self.temp_hot_c:
            raise ProfileValidationError(f"month {self.month}: expected cold <= avg <= hot")
        if self.wind_gust_max_kmh < self.wind_speed.min:
            raise ProfileValidationError(
                f"month {self.month}: gust max below the minimum wind speed"
            )
        for direction in self.preferred_wind_directions:
            if direction not in WIND_DIRECTIONS:
                raise ProfileValidationError(f"unknown wind direction: {direction}")


@dataclass(frozen=True)
class ClimateProfile:
    """A named climate preset with twelve operational months."""

    id: str
    slug: str
    display_name: str
    aliases: tuple[str, ...]
    family: str
    source: str
    hemisphere: str
    version: int
    field_provenance: Mapping[str, str]
    months: tuple[MonthProfile, ...]

    def __post_init__(self) -> None:
        if len(self.months) != 12:
            raise ProfileValidationError(f"{self.slug}: expected 12 months")
        if [month.month for month in self.months] != list(range(1, 13)):
            raise ProfileValidationError(f"{self.slug}: months must be 1..12 in order")

    def month(self, month: int) -> MonthProfile:
        if not 1 <= month <= 12:
            raise ProfileValidationError(f"month out of range: {month}")
        return self.months[month - 1]

    def matches(self, value: str) -> bool:
        needle = value.strip().lower()
        return needle in {self.slug, self.id, *self.aliases}


@dataclass(frozen=True)
class EffectiveMonthProfile:
    """Hard ranges for one channel and one month, after the channel overrides.

    ``provenance`` names the winning source for every field, so the admin can
    see whether a value comes from the workbook, the project or an override.
    """

    profile: ClimateProfile
    month: MonthProfile
    temp_min: NumericRange
    temp_max: NumericRange
    humidity: NumericRange
    wind_speed: NumericRange
    wind_gust: NumericRange
    cloud_cover: NumericRange
    visibility: NumericRange
    pressure: NumericRange
    precipitation_probability: float
    preferred_wind_directions: tuple[str, ...]
    overrides_applied: tuple[str, ...]
    provenance: Mapping[str, str]

    @property
    def temp_avg_c(self) -> float:
        return self.month.temp_avg_c

    def to_dict(self) -> dict[str, Any]:
        return {
            "preset": self.profile.slug,
            "preset_version": self.profile.version,
            "month": self.month.month,
            "precipitation_probability": self.precipitation_probability,
            "temp_min_c": self.temp_min.to_dict(),
            "temp_max_c": self.temp_max.to_dict(),
            "humidity_pct": self.humidity.to_dict(),
            "wind_speed_kmh": self.wind_speed.to_dict(),
            "wind_gust_kmh": self.wind_gust.to_dict(),
            "cloud_cover_pct": self.cloud_cover.to_dict(),
            "visibility_km": self.visibility.to_dict(),
            "pressure_hpa": self.pressure.to_dict(),
            "preferred_wind_directions": list(self.preferred_wind_directions),
            "overrides_applied": list(self.overrides_applied),
            "provenance": dict(self.provenance),
        }


def _coerce_range(field: str, value: Any) -> NumericRange:
    """Validate one ``{"min": x, "max": y}`` override entry."""
    if not isinstance(value, Mapping):
        raise ProfileValidationError(f"{field}: expected a mapping with min and max")
    if set(value) != {"min", "max"}:
        raise ProfileValidationError(f"{field}: expected exactly the keys min and max")

    try:
        low = float(value["min"])
        high = float(value["max"])
    except (TypeError, ValueError) as error:
        raise ProfileValidationError(f"{field}: min and max must be numbers") from error

    if low != low or high != high:  # NaN guard without importing math
        raise ProfileValidationError(f"{field}: NaN is not a valid bound")

    bounds = GLOBAL_BOUNDS.get(field)
    if bounds is None:
        raise ProfileValidationError(f"{field}: unknown parameter")
    if low < bounds[0] or high > bounds[1]:
        raise ProfileValidationError(
            f"{field}: {low}..{high} outside the physical bounds {bounds[0]}..{bounds[1]}"
        )
    if field in PERCENT_FIELDS and (low < 0.0 or high > 100.0):
        raise ProfileValidationError(f"{field}: percentages must stay within 0..100")
    if field in NON_NEGATIVE_FIELDS and low < 0.0:
        raise ProfileValidationError(f"{field}: values cannot be negative")

    return NumericRange(min=low, max=high)


def validate_overrides(overrides: Mapping[str, Any] | None) -> dict[str, NumericRange]:
    """Validate a channel override payload and return typed ranges.

    Cross-field rules mirror the invariants the generator enforces, so an
    impossible configuration is rejected when it is saved, not when it runs.
    """
    if not overrides:
        return {}

    ranges = {field: _coerce_range(field, value) for field, value in overrides.items()}

    if "wind_speed_kmh" in ranges and "wind_gust_kmh" in ranges:
        if ranges["wind_gust_kmh"].max < ranges["wind_speed_kmh"].max:
            raise ProfileValidationError(
                "wind_gust_kmh.max must be greater than or equal to wind_speed_kmh.max"
            )

    if "temp_min_c" in ranges and "temp_max_c" in ranges:
        if ranges["temp_min_c"].min > ranges["temp_max_c"].max:
            raise ProfileValidationError("temp_min_c and temp_max_c cannot produce a valid day")

    return ranges


# Field in the profile JSON that decides the provenance of each effective field.
_PROVENANCE_SOURCE = {
    "temp_min_c": "temp_cold_c",
    "temp_max_c": "temp_hot_c",
    "humidity_pct": "humidity_min_pct",
    "wind_speed_kmh": "wind_speed_min_kmh",
    "wind_gust_kmh": "wind_gust_max_kmh",
    "cloud_cover_pct": "cloud_cover_min_pct",
    "visibility_km": "visibility_min_km",
    "pressure_hpa": "pressure_min_hpa",
    "precipitation_probability": "precipitation_probability",
}


def resolve_effective_profile(
    profile: ClimateProfile,
    month: int,
    overrides: Mapping[str, Any] | None = None,
) -> EffectiveMonthProfile:
    """Combine a preset month with the channel overrides.

    Precedence for the *generation ranges*: the channel override wins, then the
    stable project profile, then the workbook static data. A channel override can
    narrow or widen a range, but never beyond ``GLOBAL_BOUNDS``.
    """
    month_profile = profile.month(month)
    ranges = validate_overrides(overrides)

    temp_min = ranges.get("temp_min_c") or NumericRange(
        month_profile.temp_cold_c, month_profile.temp_avg_c
    )
    temp_max = ranges.get("temp_max_c") or NumericRange(
        month_profile.temp_avg_c, month_profile.temp_hot_c
    )
    wind_gust = ranges.get("wind_gust_kmh") or NumericRange(
        month_profile.wind_speed.min, month_profile.wind_gust_max_kmh
    )

    probability_range = ranges.get("precipitation_probability_pct")
    if probability_range is None:
        probability = month_profile.precipitation_probability
    else:
        probability = (
            probability_range.clamp(month_profile.precipitation_probability * 100.0) / 100.0
        )

    provenance = {
        effective: profile.field_provenance.get(source, "project_default")
        for effective, source in _PROVENANCE_SOURCE.items()
    }
    for field in ranges:
        effective = (
            "precipitation_probability" if field == "precipitation_probability_pct" else field
        )
        provenance[effective] = "admin_override"

    return EffectiveMonthProfile(
        profile=profile,
        month=month_profile,
        temp_min=temp_min,
        temp_max=temp_max,
        humidity=ranges.get("humidity_pct") or month_profile.humidity,
        wind_speed=ranges.get("wind_speed_kmh") or month_profile.wind_speed,
        wind_gust=wind_gust,
        cloud_cover=ranges.get("cloud_cover_pct") or month_profile.cloud_cover,
        visibility=ranges.get("visibility_km") or month_profile.visibility,
        pressure=ranges.get("pressure_hpa") or month_profile.pressure,
        precipitation_probability=probability,
        preferred_wind_directions=month_profile.preferred_wind_directions,
        overrides_applied=tuple(sorted(ranges)),
        provenance=provenance,
    )


@dataclass(frozen=True)
class ProfileCatalog:
    """The twelve operational presets, loadable by slug, id or alias."""

    schema_version: int
    defaults: Mapping[str, Any]
    climates: tuple[ClimateProfile, ...]
    source_catalog_sha256: str
    source_workbook_sha256: str
    derivation: Mapping[str, str]

    def __len__(self) -> int:
        return len(self.climates)

    def __iter__(self):
        return iter(self.climates)

    def slugs(self) -> tuple[str, ...]:
        return tuple(climate.slug for climate in self.climates)

    def get(self, value: str) -> ClimateProfile:
        if not isinstance(value, str) or not value.strip():
            raise UnknownProfileError("a preset slug is required")
        for climate in self.climates:
            if climate.matches(value):
                return climate
        raise UnknownProfileError(f"unknown preset {value!r}; available: {', '.join(self.slugs())}")


def _parse_month(payload: Mapping[str, Any]) -> MonthProfile:
    return MonthProfile(
        month=int(payload["month"]),
        name=str(payload["name"]),
        precipitation_probability=float(payload["precipitation_probability"]),
        temp_cold_c=float(payload["temp_cold_c"]),
        temp_avg_c=float(payload["temp_avg_c"]),
        temp_hot_c=float(payload["temp_hot_c"]),
        humidity=NumericRange(
            float(payload["humidity_min_pct"]), float(payload["humidity_max_pct"])
        ),
        wind_speed=NumericRange(
            float(payload["wind_speed_min_kmh"]), float(payload["wind_speed_max_kmh"])
        ),
        wind_gust_max_kmh=float(payload["wind_gust_max_kmh"]),
        cloud_cover=NumericRange(
            float(payload["cloud_cover_min_pct"]), float(payload["cloud_cover_max_pct"])
        ),
        visibility=NumericRange(
            float(payload["visibility_min_km"]), float(payload["visibility_max_km"])
        ),
        pressure=NumericRange(
            float(payload["pressure_min_hpa"]), float(payload["pressure_max_hpa"])
        ),
        preferred_wind_directions=tuple(payload.get("preferred_wind_directions") or ()),
    )


def _parse_climate(payload: Mapping[str, Any]) -> ClimateProfile:
    return ClimateProfile(
        id=str(payload["id"]),
        slug=str(payload["slug"]),
        display_name=str(payload["display_name"]),
        aliases=tuple(payload.get("aliases") or ()),
        family=str(payload["family"]),
        source=str(payload["source"]),
        hemisphere=str(payload.get("hemisphere", "north")),
        version=int(payload.get("version", 1)),
        field_provenance=dict(payload.get("field_provenance") or {}),
        months=tuple(_parse_month(each) for each in payload["months"]),
    )


def load_profiles(path: Path | None = None) -> ProfileCatalog:
    """Read and validate ``climate_profiles.json``."""
    source = Path(path) if path is not None else DEFAULT_PROFILES_PATH
    payload = json.loads(source.read_text(encoding="utf-8"))

    if payload.get("schema_version") != 1:
        raise ProfileValidationError(f"unsupported profile schema: {payload.get('schema_version')}")

    climates = tuple(_parse_climate(each) for each in payload["climates"])
    if len(climates) != 12:
        raise ProfileValidationError(f"expected 12 climates, found {len(climates)}")

    slugs = [climate.slug for climate in climates]
    if len(set(slugs)) != len(slugs):
        raise ProfileValidationError("duplicate preset slug in the profile catalog")

    return ProfileCatalog(
        schema_version=int(payload["schema_version"]),
        defaults=dict(payload.get("defaults") or {}),
        climates=climates,
        source_catalog_sha256=str(payload.get("source_catalog_sha256", "")),
        source_workbook_sha256=str(payload.get("source_workbook_sha256", "")),
        derivation=dict(payload.get("derivation") or {}),
    )
